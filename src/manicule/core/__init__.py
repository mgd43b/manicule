"""Core: the types and protocols everything else is written against.

Core carries no implementation dependencies. Importing it must not pull in a vector store,
a model runtime, an HTTP framework or an inference library — that boundary is what lets a
plugin author depend on manicule's contracts without inheriting its stack, and it is
enforced by a test rather than by convention.
"""

